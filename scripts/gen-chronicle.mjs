// One-off: build src/shared/config/chronicle.ts from the fact-checked content
// workflow output. Keeps the topic META here; injects the cleaned entries.
import { readFileSync, writeFileSync } from 'fs'

const OUT = process.argv[2]
const TARGET = 'src/shared/config/chronicle.ts'
const d = JSON.parse(readFileSync(OUT, 'utf8'))
const r = typeof d.result === 'string' ? JSON.parse(d.result) : d.result
const pools = r.checked?.cleaned?.length ? r.checked.cleaned : r.pools

const META = [
  { key: 'cosmos', src: 'cosmos', name: 'Cosmos', icon: 'Planet', blurb: 'Stars, space, and the scale of it all' },
  { key: 'nature', src: 'nature', name: 'Nature & Earth', icon: 'Leaf', blurb: 'The living world and the planet beneath it' },
  { key: 'history', src: 'history', name: 'History', icon: 'Scroll', blurb: 'Surprising truths from the ages' },
  { key: 'wisdom', src: 'wisdom', name: 'Timeless Wisdom', icon: 'Feather', blurb: 'Maxims that have outlasted empires' }
]

const findPool = (src) =>
  pools.find((p) => (p.topicId || '').includes(src) || (p.topicName || '').toLowerCase().includes(src))

const q = (s) => JSON.stringify(s)

let topicsSrc = ''
for (const m of META) {
  const pool = findPool(m.src)
  if (!pool) throw new Error('no pool for ' + m.src)
  const seen = new Set()
  const entries = pool.entries.filter((e) => e.id && e.fact && !seen.has(e.id) && seen.add(e.id))
  const lines = entries
    .map((e) => `      { id: ${q(e.id)}, teaser: ${q(e.teaser || '')}, fact: ${q(e.fact)} }`)
    .join(',\n')
  topicsSrc += `  {
    id: ${q(m.key)},
    name: ${q(m.name)},
    icon: ${q(m.icon)},
    blurb: ${q(m.blurb)},
    entries: [
${lines}
    ]
  },\n`
}

const header = `// ---------------------------------------------------------------------------
// QuestDay — the Expedition Chronicle (reward CONTENT, not tunables).
//
// When you chart a realm region, your expedition "returns with" a piece of
// knowledge you chose to learn. Each topic is a pool of short, surprising,
// awe-leaning, TRUE entries. Design (research-backed): tease-then-reveal — the
// \`teaser\` opens a curiosity gap (with a foothold), the \`fact\` is the payoff.
//
// LICENSING: facts are not copyrightable (Feist v. Rural) — every entry is
// written in original words, seeded from public-domain knowledge and
// fact-checked. The Wisdom pool quotes ONLY public-domain authors. Nothing is
// copied verbatim from Wikipedia/quote sites (CC-BY-SA is viral).
//
// Generated by scripts/gen-chronicle.mjs from the content workflow; a region is
// charted once, so even a single-topic player needs only ~one entry per region.
// Icons are Phosphor names, mapped to components in the view.
// ---------------------------------------------------------------------------

export interface ChronicleEntry {
  id: string
  /** A one-line, gap-opening setup in the expedition's voice (no spoiler). */
  teaser: string
  /** The surprising, true payoff (1–2 sentences, original wording). */
  fact: string
}

export interface ChronicleTopic {
  id: string
  name: string
  /** Phosphor icon name (mapped to a component in the view). */
  icon: string
  blurb: string
  entries: ChronicleEntry[]
}

export const chronicleTopics: ChronicleTopic[] = [
`

const footer = `]

export function topicById(id: string): ChronicleTopic | undefined {
  return chronicleTopics.find((t) => t.id === id)
}

export function entryById(topicId: string, entryId: string): ChronicleEntry | undefined {
  return topicById(topicId)?.entries.find((e) => e.id === entryId)
}
`

writeFileSync(TARGET, header + topicsSrc + footer)
const counts = META.map((m) => `${m.key}=${findPool(m.src).entries.length}`).join(', ')
console.log('wrote ' + TARGET + ' | ' + counts)
console.log('first ids:', META.map((m) => `${m.key}:${findPool(m.src).entries[0].id}`).join('  '))
